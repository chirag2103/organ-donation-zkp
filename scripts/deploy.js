'use strict';

/**
 * scripts/deploy.js
 * ─────────────────────────────────────────────────────────────────────────────
 * Sequential deployment script for all 5 contracts.
 * Registers test credential Merkle roots for all 6 roles.
 * Exports all addresses to deployments/localhost.json.
 *
 * Usage:  npx hardhat run scripts/deploy.js --network localhost
 * ─────────────────────────────────────────────────────────────────────────────
 */

const { ethers } = require('hardhat');
const path       = require('path');
const fs         = require('fs');

// ── Test Merkle roots (one per role) ─────────────────────────────────────────
// These are keccak256 hashes that represent the root of a test credential tree.
// Replace with real Poseidon Merkle roots generated by setupCeremony.js in prod.
const TEST_MERKLE_ROOTS = {
  DOCTOR:      '0x1a2b3c4d5e6f7080919293949596979899a0a1a2a3a4a5a6a7a8a9aaabacadae',
  COORDINATOR: '0x2b3c4d5e6f7080919293949596979899a0a1a2a3a4a5a6a7a8a9aaabacadaeb0',
  PROCUREMENT: '0x3c4d5e6f7080919293949596979899a0a1a2a3a4a5a6a7a8a9aaabacadaeb0c1',
  MATCHING:    '0x4d5e6f7080919293949596979899a0a1a2a3a4a5a6a7a8a9aaabacadaeb0c1d2',
  TRANSPORTER: '0x5e6f7080919293949596979899a0a1a2a3a4a5a6a7a8a9aaabacadaeb0c1d2e3',
  SURGEON:     '0x6f7080919293949596979899a0a1a2a3a4a5a6a7a8a9aaabacadaeb0c1d2e3f4',
};

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log('\n═══════════════════════════════════════════════════');
  console.log('  ZKP Organ Donation System — Deployment');
  console.log('═══════════════════════════════════════════════════');
  console.log('  Deployer:', deployer.address);
  const balance = await ethers.provider.getBalance(deployer.address);
  console.log('  Balance: ', ethers.formatEther(balance), 'ETH');
  console.log('───────────────────────────────────────────────────\n');

  // ── Step 1: Deploy ZKPVerifier ────────────────────────────────────────────
  console.log('1. Deploying ZKPVerifier...');
  const ZKPVerifier = await ethers.getContractFactory('ZKPVerifier');
  const zkpVerifier = await ZKPVerifier.deploy(ethers.ZeroAddress);
  await zkpVerifier.waitForDeployment();
  const zkpAddr = await zkpVerifier.getAddress();
  console.log('   ✓ ZKPVerifier deployed at:', zkpAddr);

  // ── Step 2: Deploy RoleRegistry ──────────────────────────────────────────
  console.log('\n2. Deploying RoleRegistry...');
  const RoleRegistry = await ethers.getContractFactory('RoleRegistry');
  const roleRegistry = await RoleRegistry.deploy();
  await roleRegistry.waitForDeployment();
  const roleRegAddr = await roleRegistry.getAddress();
  console.log('   ✓ RoleRegistry deployed at:', roleRegAddr);

  // ── Step 3: Deploy PFEKeyIssuer ───────────────────────────────────────────
  console.log('\n3. Deploying PFEKeyIssuer...');
  const PFEKeyIssuer = await ethers.getContractFactory('PFEKeyIssuer');
  const pfeKeyIssuer = await PFEKeyIssuer.deploy(zkpAddr, roleRegAddr);
  await pfeKeyIssuer.waitForDeployment();
  const pfeAddr = await pfeKeyIssuer.getAddress();
  console.log('   ✓ PFEKeyIssuer deployed at:', pfeAddr);

  // ── Step 4: Deploy OrganRegistry ─────────────────────────────────────────
  console.log('\n4. Deploying OrganRegistry...');
  const OrganRegistry = await ethers.getContractFactory('OrganRegistry');
  const organRegistry = await OrganRegistry.deploy(pfeAddr);
  await organRegistry.waitForDeployment();
  const organAddr = await organRegistry.getAddress();
  console.log('   ✓ OrganRegistry deployed at:', organAddr);

  // ── Step 5: Deploy LifecycleManager ──────────────────────────────────────
  console.log('\n5. Deploying LifecycleManager...');
  const LifecycleManager = await ethers.getContractFactory('LifecycleManager');
  const lifecycleMgr = await LifecycleManager.deploy(organAddr, pfeAddr);
  await lifecycleMgr.waitForDeployment();
  const lifecycleAddr = await lifecycleMgr.getAddress();
  console.log('   ✓ LifecycleManager deployed at:', lifecycleAddr);

  // ── Step 6: Wire LifecycleManager into OrganRegistry ─────────────────────
  console.log('\n6. Configuring contract links...');
  const setMgrTx = await organRegistry.setLifecycleManager(lifecycleAddr);
  await setMgrTx.wait();
  console.log('   ✓ LifecycleManager set in OrganRegistry');

  // ── Step 7: Register test credential Merkle roots for all 6 roles ─────────
  console.log('\n7. Registering test credential Merkle roots...');
  const roleNames = ['DOCTOR', 'COORDINATOR', 'PROCUREMENT', 'MATCHING', 'TRANSPORTER', 'SURGEON'];
  for (let roleId = 0; roleId < 6; roleId++) {
    const roleName = roleNames[roleId];
    const merkleRoot = TEST_MERKLE_ROOTS[roleName];
    const tx = await roleRegistry.registerCredentialRoot(roleId, merkleRoot);
    await tx.wait();
    console.log(`   ✓ Role ${roleId} (${roleName}): root = ${merkleRoot.slice(0, 18)}...`);
  }

  // ── Step 8: Export deployment addresses ───────────────────────────────────
  console.log('\n8. Exporting deployment addresses...');
  const deploymentData = {
    ZKPVerifier:      zkpAddr,
    RoleRegistry:     roleRegAddr,
    PFEKeyIssuer:     pfeAddr,
    OrganRegistry:    organAddr,
    LifecycleManager: lifecycleAddr,
    deployer:         deployer.address,
    network:          (await ethers.provider.getNetwork()).name,
    deployedAt:       new Date().toISOString(),
    testMerkleRoots:  TEST_MERKLE_ROOTS,
  };

  const outDir  = path.join(__dirname, '..', 'deployments');
  const outPath = path.join(outDir, 'localhost.json');
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(deploymentData, null, 2));

  // Also copy to src for frontend use
  const srcDeployPath = path.join(__dirname, '..', 'src', 'deployments.json');
  fs.writeFileSync(srcDeployPath, JSON.stringify(deploymentData, null, 2));

  console.log('   ✓ Addresses written to deployments/localhost.json');
  console.log('   ✓ Addresses copied to src/deployments.json');

  console.log('\n═══════════════════════════════════════════════════');
  console.log('  Deployment complete!');
  console.log('═══════════════════════════════════════════════════');
  console.log('  ZKPVerifier     :', zkpAddr);
  console.log('  RoleRegistry    :', roleRegAddr);
  console.log('  PFEKeyIssuer    :', pfeAddr);
  console.log('  OrganRegistry   :', organAddr);
  console.log('  LifecycleManager:', lifecycleAddr);
  console.log('═══════════════════════════════════════════════════\n');
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('Deployment failed:', err);
    process.exit(1);
  });
